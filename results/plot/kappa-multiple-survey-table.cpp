// Extract IPT greedy-plus-merge cuboid counts for the structured
// multiple-survey scenarios, and emit a stand-alone LaTeX table.

#include "IPTPlot.hpp"

#include <charconv>
#include <cmath>
#include <cstdio>
#include <map>
#include <ranges>
#include <string>
#include <string_view>

namespace
{
  struct Measurement
  {
    long points{};
    long cuboids{};
  };

  auto parse_long (std::string_view text) -> long
  {
    auto value {0L};
    auto const result
      { std::from_chars (text.data(), text.data() + text.size(), value) };
    if ( result.ec != std::errc {}
       || result.ptr != text.data() + text.size()
       )
    {
      return 0L;
    }
    return value;
  }

  auto format_integer (long value) -> std::string
  {
    auto digits {std::to_string (value)};
    auto output {std::string {}};
    auto const first_group {digits.size() % 3};
    auto index {std::size_t {0}};

    if (first_group != 0)
    {
      output += digits.substr (0, first_group);
      index = first_group;
      if (index < digits.size())
      {
        output += "\\,";
      }
    }

    while (index < digits.size())
    {
      output += digits.substr (index, 3);
      index += 3;
      if (index < digits.size())
      {
        output += "\\,";
      }
    }

    return output;
  }

  auto format_ratio (long cuboids, long points) -> std::string
  {
    if (points <= 0)
    {
      return "--";
    }

    auto const value
      { static_cast<double> (cuboids) / static_cast<double> (points) };
    char buffer[64];
    std::snprintf (buffer, sizeof (buffer), "%.6f", value);
    return buffer;
  }
}

auto main() -> int
{
  using namespace ipt_plot;

  auto const platform_id {reference_platform_id (load_platforms())};
  auto const reference_config {std::string {reference_cache_config()}};
  auto values {std::map<std::string, Measurement>{}};

  visit_rows
    ( [&] (auto const& platform, auto const& meta, auto const& row)
      {
        if ( platform.id != platform_id
           || meta.cache_kind != "cache-dependent"
           || meta.config != reference_config
           || row.value ("algorithm") != "greedy-plus-merge"
           || row.value ("metric") != "cuboids"
           )
        {
          return;
        }

        auto const scenario {std::string {row.value ("scenario")}};
        if (!is_multiple_survey (scenario) || values.contains (scenario))
        {
          return;
        }

        values[scenario] = Measurement
          { .points = parse_long (row.value ("point_count"))
          , .cuboids = parse_long (row.value ("value"))
          };
      }
    );

  std::printf ("%% Auto-generated by results/plot/kappa-multiple-survey-table.cpp.\n");
  std::printf ("%% Reference platform: %s.\n", platform_id.c_str());
  std::printf ("%% Reference IPT configuration: %s.\n", reference_config.c_str());
  std::printf ("{\n");
  std::printf ("\\begin{tabular}{lrrr}\n");
  std::printf ("\\toprule\n");
  std::printf ("Scenario & Points & $\\kappa$ & $\\kappa/N$ \\\\\n");
  std::printf ("\\midrule\n");

  std::ranges::for_each
    ( structured_scenarios()
    , [&] (auto const& scenario)
      {
        if (auto const* measurement = value_ptr (values, scenario))
        {
          auto const label {structured_scenario_label (scenario)};
          std::printf
            ( "\\texttt{%s} & %s & %s & %s \\\\\n"
            , label.c_str()
            , format_integer (measurement->points).c_str()
            , format_integer (measurement->cuboids).c_str()
            , format_ratio
                ( measurement->cuboids
                , measurement->points
                ).c_str()
            );
        }
      }
    );

  std::printf ("\\bottomrule\n");
  std::printf ("\\end{tabular}\n");
  std::printf ("}\n");

  return 0;
}